# Aquest programa demana dos nombres i calcula la suma, la resta, la multiplicació i la divisió.

num1 = float(input("Primer nombre: "))
num2 = float(input("Segon nombre: "))

print("Suma: " + str(num1 + num2))
print("Resta: " + str(num1 - num2))
print("Multiplicació: " + str(num1 * num2))
print("Divisió: " + str(num1 / num2))