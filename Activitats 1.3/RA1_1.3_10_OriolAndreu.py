# Aquest programa calcula la mitjana de tres notes.

nota1 = float(input("Primera nota: "))
nota2 = float(input("Segona nota: "))
nota3 = float(input("Tercera nota: "))

mitjana = (nota1 + nota2 + nota3) / 3

print("Mitjana: " + str(mitjana))